package processors

import (
	"encoding/json"
	"fmt"
	"io"
	"strings"
	"time"

	"github.com/dbo-studio/dbo/internal/app/dto"
	databaseContract "github.com/dbo-studio/dbo/internal/database/contract"
	databaseCore "github.com/dbo-studio/dbo/internal/database/core"
	"github.com/dbo-studio/dbo/pkg/csv"
	"github.com/dbo-studio/dbo/pkg/helper"
	"github.com/samber/lo"
)

func sqlExportHeader() string {
	return "-- Export Data\n-- Generated by DBO Studio\n-- Generated on: " + time.Now().Format("2006-01-02 15:04:05") + "\n\n"
}

// tableWriter writes one table's rows to w in the requested format as chunks
// arrive. quote is set for multi-table exports so names with spaces or
// reserved words stay valid; single-query exports keep the caller's name as is.
type tableWriter struct {
	w              io.Writer
	format         string
	table          string
	schema         string
	connectionType string
	quote          bool
	skip           map[string]bool
	overrideIdent  bool
	started        bool
	rows           int
	columns        int
}

func newTableWriter(w io.Writer, format, table, connectionType string, quote bool, ddl *databaseContract.TableDDL) *tableWriter {
	t := &tableWriter{w: w, format: format, table: table, connectionType: connectionType, quote: quote}

	if ddl != nil {
		t.skip = lo.SliceToMap(ddl.GeneratedColumns, func(c string) (string, bool) { return c, true })
		t.overrideIdent = ddl.OverridingIdentity
	}

	return t
}

func (t *tableWriter) ident(name string) string {
	if !t.quote {
		return name
	}

	return databaseCore.QuoteIdent(t.connectionType, name)
}

func (t *tableWriter) qualifiedTable() string {
	if t.schema == "" {
		return t.ident(t.table)
	}

	return databaseCore.QuoteIdent(t.connectionType, t.schema) + "." + databaseCore.QuoteIdent(t.connectionType, t.table)
}

func (t *tableWriter) write(columns []dto.Column, rows []map[string]any) error {
	t.columns = len(columns)
	names := lo.Map(columns, func(col dto.Column, _ int) string { return col.Name })

	var err error

	switch t.format {
	case "sql":
		err = t.writeSQL(names, rows)
	case "json":
		err = t.writeJSON(rows)
	case "csv":
		if !t.started {
			_, err = io.WriteString(t.w, csv.Header(names))
		}

		if err == nil {
			_, err = io.WriteString(t.w, csv.Rows(names, rows))
		}
	default:
		err = fmt.Errorf("unsupported format: %s", t.format)
	}

	t.started = true
	t.rows += len(rows)

	return err
}

func (t *tableWriter) finish() error {
	if t.format != "json" {
		return nil
	}

	if !t.started {
		_, err := io.WriteString(t.w, "[]")

		return err
	}

	_, err := io.WriteString(t.w, "\n]")

	return err
}

func (t *tableWriter) writeJSON(rows []map[string]any) error {
	prefix := ",\n"
	if !t.started {
		prefix = "[\n"
	}

	for _, row := range rows {
		encoded, err := json.Marshal(row)
		if err != nil {
			return err
		}

		if _, err := io.WriteString(t.w, prefix); err != nil {
			return err
		}

		if _, err := t.w.Write(encoded); err != nil {
			return err
		}

		prefix = ",\n"
	}

	return nil
}

func (t *tableWriter) writeSQL(names []string, rows []map[string]any) error {
	if len(rows) == 0 {
		return nil
	}

	names = lo.Reject(names, func(n string, _ int) bool { return t.skip[n] })

	overriding := ""
	if t.overrideIdent {
		overriding = " OVERRIDING SYSTEM VALUE"
	}

	var sql strings.Builder

	fmt.Fprintf(&sql, "INSERT INTO %s (%s)%s VALUES\n", t.qualifiedTable(), strings.Join(lo.Map(names, func(n string, _ int) string { return t.ident(n) }), ", "), overriding)

	for i, row := range rows {
		values := make([]string, len(names))

		for j, n := range names {
			value, err := helper.FormatSQLValueForDriver(t.connectionType, row[n])
			if err != nil {
				return fmt.Errorf("column %s: %w", n, err)
			}

			values[j] = value
		}

		sql.WriteString("(" + strings.Join(values, ", ") + ")")

		if i < len(rows)-1 {
			sql.WriteString(",\n")
		} else {
			sql.WriteString(";\n")
		}
	}

	_, err := io.WriteString(t.w, sql.String())

	return err
}
